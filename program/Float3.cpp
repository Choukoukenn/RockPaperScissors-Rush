#include "Float3.h"
#include "Main.h"
//---------------------------------------------------------------------------------
//	コンストラクタ
//---------------------------------------------------------------------------------
Float3::Float3()
{
	x = 0.0f;
	y = 0.0f;
	z = 0.0f;
}
Float3::Float3( float x, float y, float z )
{
	this->x = x;
	this->y = y;
	this->z = z;
}
Float3::Float3( VECTOR v )
{
	x = v.x;
	y = v.y;
	z = v.z;
}
//---------------------------------------------------------------------------------
//	ゼロ初期化（ＸＹＺの値を０にします）
//---------------------------------------------------------------------------------
void Float3::Clear()
{
	x = 0.0f;
	y = 0.0f;
	z = 0.0f;
}
//---------------------------------------------------------------------------------
//	値のセット（ＸＹＺをそれぞれ受け取るバージョン）
//---------------------------------------------------------------------------------
void Float3::Set( float x, float y, float z )
{
	this->x = x;
	this->y = y;
	this->z = z;
}
//---------------------------------------------------------------------------------
//	値のセット（ Float3 を受け取るバージョン ）
//---------------------------------------------------------------------------------
void Float3::Set( Float3 &f3 )
{
	x = f3.x;
	y = f3.y;
	z = f3.z;
}
//---------------------------------------------------------------------------------
//	長さ取得
//---------------------------------------------------------------------------------
float Float3::GetLength()
{
	return sqrtf( x * x + y * y + z * z );
}
//---------------------------------------------------------------------------------
//	正規化（ベクトルの長さを１にする）
//---------------------------------------------------------------------------------
void Float3::Normalize()
{
	float length = GetLength();
	if( length > 0.0f ){
		x = x / length;
		y = y / length;
		z = z / length;
	}
}
//---------------------------------------------------------------------------------
//	長さ設定
//---------------------------------------------------------------------------------
void Float3::SetLength( float length )
{
	Normalize();
	x = x * length;
	y = y * length;
	z = z * length;
}

//---------------------------------------------------------------------------------
//	= 演算子のオーバーロード
//---------------------------------------------------------------------------------
Float3& Float3::operator = ( const Float3 &f3 )
{
	x = f3.x;
	y = f3.y; 
	z = f3.z; 
	return *this; 
}
//---------------------------------------------------------------------------------
//	+= 演算子のオーバーロード
//---------------------------------------------------------------------------------
Float3& Float3::operator += ( const Float3 &f3 )
{
	x += f3.x;
	y += f3.y;
	z += f3.z;
	return *this;
}
//---------------------------------------------------------------------------------
//	-= 演算子のオーバーロード
//---------------------------------------------------------------------------------
Float3& Float3::operator -= ( const Float3 &f3 )
{
	x -= f3.x;
	y -= f3.y;
	z -= f3.z;
	return *this;
}
//---------------------------------------------------------------------------------
//	*= 演算子のオーバーロード
//---------------------------------------------------------------------------------
Float3& Float3::operator *= ( const float f )
{
	x *= f;
	y *= f;
	z *= f;
	return *this;
}
//---------------------------------------------------------------------------------
//	/= 演算子のオーバーロード
//---------------------------------------------------------------------------------
Float3& Float3::operator /= ( const float f )
{
	x /= f;
	y /= f;
	z /= f;
	return *this;
}

//---------------------------------------------------------------------------------
//	+ 演算子のオーバーロード
//---------------------------------------------------------------------------------
Float3 operator + ( const Float3 &f3_1, const Float3 &f3_2 )
{
	Float3 ret;
	ret.x = f3_1.x + f3_2.x;
	ret.y = f3_1.y + f3_2.y;
	ret.z = f3_1.z + f3_2.z;
	return ret;
}
//---------------------------------------------------------------------------------
//	- 演算子のオーバーロード
//---------------------------------------------------------------------------------
Float3 operator - ( const Float3 &f3_1, const Float3 &f3_2 )
{
	Float3 ret;
	ret.x = f3_1.x - f3_2.x;
	ret.y = f3_1.y - f3_2.y;
	ret.z = f3_1.z - f3_2.z;
	return ret;
}
//---------------------------------------------------------------------------------
//	* 演算子のオーバーロード
//---------------------------------------------------------------------------------
Float3 operator * ( const Float3 &f3, const float f )
{
	Float3 ret;
	ret.x = f3.x * f;
	ret.y = f3.y * f;
	ret.z = f3.z * f;
	return ret;
}
//---------------------------------------------------------------------------------
//	/ 演算子のオーバーロード
//---------------------------------------------------------------------------------
Float3 operator / ( const Float3 &f3, const float f )
{
	Float3 ret;
	ret.x = f3.x / f;
	ret.y = f3.y / f;
	ret.z = f3.z / f;
	return ret;
}

//---------------------------------------------------------------------------------
//	DXライブラリで使う VECTOR を返す
//---------------------------------------------------------------------------------
VECTOR Float3::VGet()
{
	VECTOR v;
	v.x = x;
	v.y = y;
	v.z = z;
	return v;
}
//---------------------------------------------------------------------------------
//	DXライブラリで使う VECTOR の値を取得して設定
//---------------------------------------------------------------------------------
void Float3::VSet( VECTOR v )
{
	x = v.x;
	y = v.y;
	z = v.z;
}

//---------------------------------------------------------------------------------
//	２つの Float3 の距離を求める
//---------------------------------------------------------------------------------
float GetFloat3Distance( Float3 &pos1, Float3 &pos2 )
{
	float x = pos1.x - pos2.x;
	float y = pos1.y - pos2.y;
	float z = pos1.z - pos2.z;
	float distance = sqrtf( x * x + y * y + z * z );
	return distance;
}
//---------------------------------------------------------------------------------
//	２つの Float3 の内積を求める
//---------------------------------------------------------------------------------
float GetFloat3Dot( Float3 &v1, Float3 &v2 )
{
	return v1.x * v2.x + v1.y * v2.y + v1.z * v2.z;
}
//---------------------------------------------------------------------------------
//	２つの Float3 の外積を求める
//---------------------------------------------------------------------------------
Float3 GetFloat3Cross( Float3 &v1, Float3 &v2 )
{
	Float3 v;
	v.x = v1.y * v2.z - v1.z * v2.y;
	v.y = v1.z * v2.x - v1.x * v2.z;
	v.z = v1.x * v2.y - v1.y * v2.x;
	return v;
}
//---------------------------------------------------------------------------------
//	Float3 を MATRIX で変換した Float3 を返す
//---------------------------------------------------------------------------------
Float3 GetFloat3VTransform( Float3 &v, MATRIX &mat )
{
	VECTOR base = v.VGet();
	VECTOR change = VTransform( base, mat );

	Float3 ret( change );
	return ret;
}
